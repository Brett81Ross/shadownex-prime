import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {GlobeController} from '../src/globe/GlobeController.js';
import {installViewportDialogs} from '../src/ui/viewportDialogs.js';
const read=p=>readFile(new URL('../'+p,import.meta.url),'utf8');
const [ui,css,html,source,reset]=await Promise.all(['src/ui/friendlyUiEnhancements.js','src/ui/viewportDialogs.css','index.html','src/globe/GlobeController.js','src/ui/sblWatch.js'].map(read));
assert.ok(ui.includes('installViewportDialogs()')&&css.includes('dialog.viewport-modal'),'visible viewport applied to all remaining modals');
assert.ok(ui.includes('threeDWorldBtn')&&html.includes('/src/ui/viewportDialogs.css'),'3D mode is opt-in and visible');
assert.ok(source.includes('createOsmBuildingsAsync')&&source.includes('createWorldTerrainAsync'),'3D uses genuine data geometry, not CSS tilt');
assert.ok(reset.includes('setWorld3D?.(false)'),'reset restores default globe');
assert.equal(typeof installViewportDialogs,'function');
const calls=[];
const C={Ion:{defaultAccessToken:''},createWorldTerrainAsync:async()=>{calls.push('terrain');return {name:'terrain'};},createOsmBuildingsAsync:async()=>{calls.push('buildings');return {show:true}},EllipsoidTerrainProvider:class{constructor(){calls.push('ellipsoid')}}};
globalThis.window={Cesium:C};
const globe=Object.create(GlobeController.prototype);
globe.viewer={terrainProvider:null,scene:{primitives:{add(tiles){calls.push('add');return tiles;}}}};
globe.settings={cesiumToken:''};globe.requestRender=()=>calls.push('render');
assert.equal((await globe.setWorld3D(true)).ok,false,'missing token must fail closed');
assert.equal(calls.length,0,'missing token does not call paid services');
globe.settings.cesiumToken='isolated-qa-token';
assert.equal((await globe.setWorld3D(true)).ok,true,'token enables genuine terrain and building layers');
assert.equal(globe.world3DMode,'on');assert.equal(globe.world3DBuildings.show,true);
assert.ok(calls.includes('terrain')&&calls.includes('buildings')&&calls.includes('add'));
const firstCount=calls.filter(x=>x==='buildings').length;
assert.equal((await globe.setWorld3D(false)).ok,true);
assert.equal(globe.world3DBuildings.show,false);
assert.equal(globe.terrainStatus,'ELLIPSOID');
assert.equal((await globe.setWorld3D(true)).ok,true);
assert.equal(calls.filter(x=>x==='buildings').length,firstCount,'existing buildings tileset is reused');
console.log('PASS: viewport modal module wiring, opt-in 3D source API, mocked terrain/buildings, reversible fallback and reset integration');
